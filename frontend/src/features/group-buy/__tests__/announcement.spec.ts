import { beforeEach, describe, expect, it, vi } from 'vitest'
import { flushPromises, mount } from '@vue/test-utils'
import AdminAnnouncementPanel from '../AdminAnnouncementPanel.vue'
import { adminGroupBuyAPI } from '@/api/groupBuy'

vi.mock('vue-i18n', () => ({ useI18n: () => ({ t: (key: string) => key }) }))
vi.mock('@/api/groupBuy', () => ({ adminGroupBuyAPI: { announcement: vi.fn(), saveAnnouncement: vi.fn() } }))
const button = (wrapper: ReturnType<typeof mount>, key: string) => wrapper.findAll('button').find(b => b.text() === `groupBuy.${key}`)!
beforeEach(() => {
  vi.resetAllMocks()
  vi.mocked(adminGroupBuyAPI.announcement).mockResolvedValue({content: 'Existing notice'})
  vi.mocked(adminGroupBuyAPI.saveAnnouncement).mockImplementation(async value => value)
})
describe('announcement editing', () => {
  it('loads persisted content, previews safely, saves multiline text, and restores defaults only after saving', async () => {
    const wrapper = mount(AdminAnnouncementPanel)
    await flushPromises()
    expect(wrapper.get('textarea').element.value).toBe('Existing notice')
    expect(button(wrapper,'announcementSave').attributes('disabled')).toBeDefined()
    await wrapper.get('textarea').setValue('公告\n<img src=x onerror=alert(1)>')
    expect(wrapper.find('img').exists()).toBe(false)
    await button(wrapper,'announcementSave').trigger('click')
    await flushPromises()
    expect(adminGroupBuyAPI.saveAnnouncement).toHaveBeenLastCalledWith({content:'公告\n<img src=x onerror=alert(1)>'})
    expect(wrapper.get('[role="status"]').text()).toBe('groupBuy.announcementSaved')
    await button(wrapper,'announcementReset').trigger('click')
    expect(adminGroupBuyAPI.saveAnnouncement).toHaveBeenCalledTimes(1)
    expect(wrapper.text()).toContain('groupBuy.subtitle')
    await button(wrapper,'announcementSave').trigger('click')
    await flushPromises()
    expect(adminGroupBuyAPI.saveAnnouncement).toHaveBeenLastCalledWith({content:''})
    wrapper.unmount()
  })
  it('keeps the draft on save failure and retries without overwriting edits', async () => {
    const wrapper = mount(AdminAnnouncementPanel)
    await flushPromises()
    await wrapper.get('textarea').setValue('Keep this draft')
    vi.mocked(adminGroupBuyAPI.saveAnnouncement).mockRejectedValueOnce(new Error('offline'))
    await button(wrapper,'announcementSave').trigger('click')
    await flushPromises()
    expect(wrapper.get('textarea').element.value).toBe('Keep this draft')
    expect(wrapper.find('[role="alert"]').exists()).toBe(true)
    await button(wrapper,'retry').trigger('click')
    await flushPromises()
    expect(adminGroupBuyAPI.saveAnnouncement).toHaveBeenCalledTimes(2)
    expect(adminGroupBuyAPI.announcement).toHaveBeenCalledTimes(1)
    wrapper.unmount()
  })
  it('does not allow overwriting an announcement when initial loading fails', async () => {
    vi.mocked(adminGroupBuyAPI.announcement).mockRejectedValueOnce(new Error('offline'))
    const wrapper = mount(AdminAnnouncementPanel)
    await flushPromises()
    expect(button(wrapper,'announcementSave').attributes('disabled')).toBeDefined()
    expect(wrapper.get('textarea').attributes('disabled')).toBeDefined()
    await button(wrapper,'retry').trigger('click')
    await flushPromises()
    expect(wrapper.get('textarea').element.value).toBe('Existing notice')
    wrapper.unmount()
  })
  it('counts Unicode characters and rejects content beyond the server limit', async () => {
    const wrapper = mount(AdminAnnouncementPanel)
    await flushPromises()
    await wrapper.get('textarea').setValue('🎉'.repeat(5000))
    expect(button(wrapper,'announcementSave').attributes('disabled')).toBeUndefined()
    await wrapper.get('textarea').setValue('中'.repeat(5001))
    expect(button(wrapper,'announcementSave').attributes('disabled')).toBeDefined()
    expect(adminGroupBuyAPI.saveAnnouncement).not.toHaveBeenCalled()
    wrapper.unmount()
  })
})
